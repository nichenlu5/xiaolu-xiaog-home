function buildKnowledgeQuestions(group) {
  return group.facts.map((fact, index) => {
    const correctPosition = index % 4;
    const answers = [fact[1]];
    let offset = 1;
    while (answers.length < 4) {
      const candidate = group.facts[(index + offset) % group.facts.length][1];
      if (!answers.includes(candidate)) answers.push(candidate);
      offset += 1;
    }
    const options = answers.slice(1);
    options.splice(correctPosition, 0, fact[1]);
    return {
      category: group.category,
      difficulty: index < 5 ? "easy" : index < 10 ? "medium" : "hard",
      question: group.template(fact[0]),
      options,
      answer: correctPosition,
      explanation: `正确答案是“${fact[1]}”。`
    };
  });
}

